async def send_phone_verification_otp(phone: str, fallback_otp: Optional[str] = None) -> Dict[str, Any]:
    """
    Initiate an SMS OTP challenge using Twilio Verify v2 API, or local dev mode.
    """
    is_twilio_configured = bool(TWILIO_ACCOUNT_SID and TWILIO_AUTH_TOKEN and TWILIO_VERIFY_SERVICE_SID)

    if SMS_PROVIDER == "twilio" or (APP_ENV == "production" and is_twilio_configured):
        if not is_twilio_configured:
            error_msg = "Twilio Verify credentials (SID, Token, Service SID) must be configured in environment."
            logger.error(error_msg)
            return {"success": False, "provider": "twilio", "error": error_msg}

        try:
            url = f"https://verify.twilio.com/v2/Services/{TWILIO_VERIFY_SERVICE_SID}/Verifications"
            async with httpx.AsyncClient(timeout=10.0) as client:
                res = await client.post(
                    url,
                    auth=(TWILIO_ACCOUNT_SID, TWILIO_AUTH_TOKEN),
                    data={
                        "To": phone,
                        "Channel": "sms"
                    }
                )
                res_data = res.json()
                if res.status_code in [200, 201] and res_data.get("status") in ["pending", "approved"]:
                    return {
                        "success": True,
                        "provider": "twilio_verify",
                        "status": res_data.get("status"),
                        "sid": res_data.get("sid"),
                        "message": f"Twilio Verify OTP challenge sent to {phone}."
                    }
                else:
                    err_detail = res_data.get("message") or f"Twilio error code {res_data.get('code', res.status_code)}"
                    logger.error(f"Twilio Verify failed: {res.status_code} - {err_detail}")
                    return {
                        "success": False,
                        "provider": "twilio_verify",
                        "error": f"Twilio Verify request failed: {err_detail}"
                    }
        except Exception as e:
            logger.error(f"Twilio Verify Exception: {str(e)}")
            return {"success": False, "provider": "twilio_verify", "error": f"Twilio connection error: {str(e)}"}

    if APP_ENV == "production":
        return {
            "success": False,
            "provider": "unconfigured",
            "error": "Real SMS verification service is not configured for production. Please configure Twilio Verify."
        }

    # Safe Local Development Console Output
    print("\n" + "=" * 55)
    print(f"📱 [DEV MODE SMS OTP] Recipient: {phone}")
    print(f"🔑 Verification Code: {fallback_otp or 'Generated by backend'}")
    print("ℹ️ (To use live SMS, set TWILIO_ACCOUNT_SID, TWILIO_AUTH_TOKEN, TWILIO_VERIFY_SERVICE_SID)")
    print("=" * 55 + "\n")

    return {
        "success": True,
        "provider": "console",
        "dev_mode": True,
        "message": "Verification code logged to console (Development Mode)."
    }

# Convenient alias
send_phone_otp = send_phone_verification_otp

async def check_phone_verification_otp(phone: str, code: str) -> Tuple[bool, str]:
    """
    Check OTP code against Twilio Verify v2 API if Twilio is active.
    Returns: (is_approved: bool, error_message: str)
    """
    is_twilio_configured = bool(TWILIO_ACCOUNT_SID and TWILIO_AUTH_TOKEN and TWILIO_VERIFY_SERVICE_SID)

    if SMS_PROVIDER == "twilio" and is_twilio_configured:
        try:
            url = f"https://verify.twilio.com/v2/Services/{TWILIO_VERIFY_SERVICE_SID}/VerificationCheck"
            async with httpx.AsyncClient(timeout=10.0) as client:
                res = await client.post(
                    url,
                    auth=(TWILIO_ACCOUNT_SID, TWILIO_AUTH_TOKEN),
                    data={
                        "To": phone,
                        "Code": code.strip()
                    }
                )
                res_data = res.json()
                if res.status_code in [200, 201] and res_data.get("status") == "approved":
                    return True, ""
                else:
                    return False, "Invalid or expired verification code."
        except Exception as e:
            logger.error(f"Twilio VerificationCheck Exception: {str(e)}")
            return False, f"Twilio verification error: {str(e)}"

    # In local development mode, verification is checked against SQLite tokens in auth_service
    return True, ""


